import sys


def sha256(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def parameter_names(params: str) -> list[str]:
    if params.strip() in {"", "void"}:
        return []
    names = []
    for parameter in params.split(","):
        match = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:\[[^]]*\])?\s*$", parameter)
        if not match:
            raise ValueError(f"cannot extract parameter name from {parameter!r}")
        names.append(match.group(1))
    return names


def generate_redirect_header(functions: list[dict]) -> str:
    lines = [
        "/* Generated by scripts/build_external_c_oracle.py; do not edit. */",
        "#ifndef FONTDONE_EXTERNAL_TRACE_REDIRECTS_H_",
        "#define FONTDONE_EXTERNAL_TRACE_REDIRECTS_H_",
    ]
    for row in functions:
        symbol = row["symbol"]
        lines.append(f"#define {symbol} fontdone_trace_{symbol}")
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def generate_reapply_header(functions: list[dict]) -> str:
    lines = [
        "/* Generated by scripts/build_external_c_oracle.py; do not edit. */",
    ]
    for row in functions:
        symbol = row["symbol"]
        lines.extend(
            [
                f"#undef {symbol}",
                f"#define {symbol} fontdone_trace_{symbol}",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def generate_trace_source(functions: list[dict]) -> str:
    lines = [
        "/* Generated by scripts/build_external_c_oracle.py; do not edit. */",
        '#include "fontdone_ffi.h"',
        "",
        "#include <stdio.h>",
        "#include <stdlib.h>",
        "",
        "static FILE* fontdone_trace_file;",
        "static unsigned long fontdone_trace_case;",
        "",
        "void fontdone_external_trace_case_begin(unsigned long case_index) {",
        "    fontdone_trace_case = case_index;",
        "    if (!fontdone_trace_file) {",
        '        const char* path = getenv("FONTDONE_EXTERNAL_TRACE_FILE");',
        '        if (path && path[0] != \'\\0\') fontdone_trace_file = fopen(path, "w");',
        "    }",
        "}",
        "",
        "static void fontdone_external_trace_call(const char* symbol) {",
        "    if (!fontdone_trace_file) return;",
        '    fprintf(fontdone_trace_file, "%lu\\t%s\\n", fontdone_trace_case, symbol);',
        "    fflush(fontdone_trace_file);",
        "}",
        "",
    ]
    for row in functions:
        symbol = row["symbol"]
        return_type = row["c_return"]
        params = row["c_params"]
        arguments = ", ".join(parameter_names(params))
        lines.extend(
            [
                f"{return_type} fontdone_trace_{symbol}({params}) {{",
                f'    fontdone_external_trace_call("{symbol}");',
            ]
        )
        if return_type == "void":
            lines.append(f"    {symbol}({arguments});")
        else:
            lines.append(f"    return {symbol}({arguments});")
        lines.extend(["}", ""])
    return "\n".join(lines)


def shared_library(cargo_target_dir: pathlib.Path) -> pathlib.Path:
    release = cargo_target_dir / "release"
    candidates = [
        release / "libfontdone_c_abi.dylib",
        release / "libfontdone_c_abi.so",
        release / "fontdone_c_abi.dll",
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise FileNotFoundError(
        "missing fontdone-c-abi shared library; run "
        "`cargo build --release -p fontdone-c-abi`"
    )


def write_if_changed(path: pathlib.Path, contents: str) -> None:
    if path.exists() and path.read_text() == contents:
        return
    path.write_text(contents)


def inspect_dynamic_dependencies(executable: pathlib.Path) -> dict:
    if shutil.which("otool"):
        command = ["otool", "-L", str(executable)]
    elif shutil.which("readelf"):
        command = ["readelf", "-d", str(executable)]
    else:
        raise OSError("neither otool nor readelf is available for dependency inspection")
    output = subprocess.run(
        command, check=True, text=True, stdout=subprocess.PIPE
    ).stdout
    lowered = output.lower()
    fontdone_present = "fontdone_c_abi" in lowered
    freetype_present = re.search(r"(?:^|[/\\s])libfreetype(?:[.\\s]|$)", lowered, re.M)
    if not fontdone_present:
        raise ValueError("external C executable does not depend on fontdone_c_abi")
    if freetype_present:
        raise ValueError("external C executable unexpectedly depends on libfreetype")
    return {
        "command": command,
        "output": output,
        "fontdone_c_abi_present": fontdone_present,
        "libfreetype_present": bool(freetype_present),
    }


def run_json(command: list[str], environment=None) -> dict:
    completed = subprocess.run(
        command,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=environment,
    )
    value = json.loads(completed.stdout)
    if not isinstance(value, dict):
        raise ValueError(f"command did not emit a JSON object: {command}")
    return value


def freetype_library(build_dir: pathlib.Path) -> pathlib.Path:
    candidates = [
        build_dir / "libfreetype.so",
        build_dir / "libfreetype.dylib",
    ]
    candidates.extend(sorted(build_dir.glob("libfreetype*.so*")))
    candidates.extend(sorted(build_dir.glob("libfreetype*.dylib")))
    candidates.extend(sorted(build_dir.glob("libfreetype*.a")))
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise FileNotFoundError(f"no pinned FreeType library in {build_dir}")


def verify_lzw_disabled_contract(
    root: pathlib.Path,
    external: pathlib.Path,
    fontdone_library: pathlib.Path,
    cargo_target_dir: pathlib.Path,
    build_manifest: pathlib.Path,
) -> None:
    case_id = "ftlzw.FT_Stream_OpenLZW.unsupported_build_error"
    fixture = root / "tests" / "fixtures" / "compressed" / "lzw" / "small-valid-pcf.Z"
    pinned_oracle = (
        root / "target" / "unified-fixtures" / "gen_unified_oracle_lzw_disabled"
    )
    probe = (
        cargo_target_dir
        / "release"
        / "examples"
        / f"optional_feature_probe{'.exe' if os.name == 'nt' else ''}"
    )
    pinned_build = root / "freetype" / "build-lzw-disabled"
    pinned_library = freetype_library(pinned_build)
    option_header = (
        root
        / "target"
        / "oracle-config"
        / "lzw-disabled"
        / "fontdone_ftoption_lzw_disabled.h"
    )
    if "#undef FT_CONFIG_OPTION_USE_LZW" not in option_header.read_text():
        raise ValueError("LZW-disabled pinned option header still enables LZW")

    pinned_environment = os.environ.copy()
    pinned_environment["LD_LIBRARY_PATH"] = str(pinned_build)
    pinned_environment["DYLD_LIBRARY_PATH"] = str(pinned_build)
    fontdone_environment = os.environ.copy()
    fontdone_environment["LD_LIBRARY_PATH"] = str(fontdone_library.parent)
    fontdone_environment["DYLD_LIBRARY_PATH"] = str(fontdone_library.parent)
    commands = {
        "pinned_c": [
            str(pinned_oracle),
            "--lzw-stream-case",
            case_id,
            str(fixture),
        ],
        "rust_ffi": [str(probe), "lzw", "rust"],
        "external_c": [
            str(external),
            "--lzw-stream-case",
            case_id,
            str(fixture),
        ],
        "wasm_host": [str(probe), "lzw", "wasm"],
    }
    outputs = {
        "pinned_c": run_json(commands["pinned_c"], pinned_environment),
        "rust_ffi": run_json(commands["rust_ffi"]),
        "external_c": run_json(commands["external_c"], fontdone_environment),
        "wasm_host": run_json(commands["wasm_host"]),
    }
    expected = outputs["pinned_c"]
    mismatches = [
        name for name, output in outputs.items() if output != expected
    ]
    status = expected.get("status", {})
    rows = expected.get("output", {}).get("rows", [])
    if (
        status.get("kind") != "error"
        or status.get("error_code") != 7
        or len(rows) != 2
        or any(row.get("status") != 7 for row in rows)
        or rows[1].get("target_stream_before")
        != rows[1].get("target_stream_after")
    ):
        raise ValueError(f"invalid pinned LZW-disabled contract output: {expected}")
    if mismatches:
        raise ValueError(
            "LZW-disabled contract mismatch: " + ", ".join(mismatches)
        )

    normalized = json.dumps(expected, sort_keys=True, separators=(",", ":"))
    ledger = {
        "schema_version": 1,
        "pinned_freetype_version": "2.14.3",
        "case_id": case_id,
        "measurement": (
            "The same null and valid argument matrix executes through an "
            "isolated pinned FreeType build, no-default-feature Rust FFI, "
            "separately linked C artifact, and no-default-feature WASM host."
        ),
        "status": "exact",
        "lanes": 4,
        "normalized_output_sha256": hashlib.sha256(
            normalized.encode()
        ).hexdigest(),
        "identity": {
            "option_header": str(option_header.relative_to(root)),
            "option_header_sha256": sha256(option_header),
            "pinned_library": str(pinned_library.relative_to(root)),
            "pinned_library_sha256": sha256(pinned_library),
            "pinned_oracle": str(pinned_oracle.relative_to(root)),
            "pinned_oracle_sha256": sha256(pinned_oracle),
            "fontdone_library": str(fontdone_library.relative_to(root)),
            "fontdone_library_sha256": sha256(fontdone_library),
            "external_c": str(external.relative_to(root)),
            "external_c_sha256": sha256(external),
            "rust_wasm_probe": str(probe.relative_to(root)),
            "rust_wasm_probe_sha256": sha256(probe),
            "external_build_manifest": str(build_manifest.relative_to(root)),
            "external_build_manifest_sha256": sha256(build_manifest),
            "fixture": str(fixture.relative_to(root)),
            "fixture_sha256": sha256(fixture),
        },
        "commands": commands,
        "outputs": outputs,
    }
    ledger_path = (
        root / "target" / "api-abi-audit" / "lzw_disabled_contract_ledger.json"
    )
    ledger_path.parent.mkdir(parents=True, exist_ok=True)
    ledger_path.write_text(json.dumps(ledger, indent=2) + "\n")
    print(
        "LZW-disabled contract: "
        f"4/4 exact sha256={ledger['normalized_output_sha256']}"
    )


