def verify_subpixel_rendering_enabled_contract(
    root: pathlib.Path,
    external: pathlib.Path,
    fontdone_library: pathlib.Path,
    cargo_target_dir: pathlib.Path,
    build_manifest: pathlib.Path,
) -> None:
    routes = {
        "ftlcdfil.FT_Library_SetLcdFilter.success_sets_none_default_light": [
            "--set-lcd-filter",
            "1",
            "0,1,2",
        ],
        "ftlcdfil.FT_Library_SetLcdFilter.error_null_library": [
            "--set-lcd-filter",
            "0",
            "1",
        ],
        "ftlcdfil.FT_Library_SetLcdFilter.error_invalid_filter": [
            "--set-lcd-filter",
            "1",
            "3,16,4,99",
        ],
        "ftlcdfil.FT_Library_SetLcdFilterWeights.success_copies_five_weights": [
            "--set-lcd-filter-weights",
            "1",
            "16,32,64,32,16,255",
        ],
        "ftlcdfil.FT_Library_SetLcdFilterWeights.error_null_library": [
            "--set-lcd-filter-weights",
            "0",
            "16,32,64,32,16",
        ],
        "ftlcdfil.FT_Library_SetLcdFilterWeights.error_null_weights": [
            "--set-lcd-filter-weights",
            "1",
            "-",
        ],
        (
            "ftlcdfil.FT_Library_SetLcdGeometry."
            "unimplemented_with_subpixel_filtering"
        ): [
            "--set-lcd-geometry",
            "1",
            "-21,0;0,0;21,0",
        ],
    }
    pinned_oracle = (
        root
        / "target"
        / "unified-fixtures"
        / "gen_unified_oracle_subpixel_rendering_enabled"
    )
    probe = (
        cargo_target_dir
        / "release"
        / "examples"
        / f"optional_feature_probe{'.exe' if os.name == 'nt' else ''}"
    )
    pinned_build = root / "freetype" / "build-subpixel-rendering-enabled"
    pinned_library = freetype_library(pinned_build)
    option_header = (
        root
        / "target"
        / "oracle-config"
        / "subpixel-rendering-enabled"
        / "fontdone_ftoption_subpixel_rendering_enabled.h"
    )
    if "#define FT_CONFIG_OPTION_SUBPIXEL_RENDERING" not in option_header.read_text():
        raise ValueError(
            "subpixel-rendering-enabled pinned option header does not enable the option"
        )

    pinned_environment = os.environ.copy()
    pinned_environment["LD_LIBRARY_PATH"] = str(pinned_build)
    pinned_environment["DYLD_LIBRARY_PATH"] = str(pinned_build)
    fontdone_environment = os.environ.copy()
    fontdone_environment["LD_LIBRARY_PATH"] = str(fontdone_library.parent)
    fontdone_environment["DYLD_LIBRARY_PATH"] = str(fontdone_library.parent)
    all_commands = {}
    all_outputs = {}
    for case_id, route in routes.items():
        commands = {
            "pinned_c": [str(pinned_oracle), *route],
            "rust_ffi": [
                str(probe),
                "subpixel-rendering",
                "rust",
                *route,
            ],
            "external_c": [str(external), *route],
            "wasm_host": [
                str(probe),
                "subpixel-rendering",
                "wasm",
                *route,
            ],
        }
        outputs = {
            "pinned_c": run_json(commands["pinned_c"], pinned_environment),
            "rust_ffi": run_json(commands["rust_ffi"]),
            "external_c": run_json(commands["external_c"], fontdone_environment),
            "wasm_host": run_json(commands["wasm_host"]),
        }
        expected = outputs["pinned_c"]
        mismatches = [
            name for name, output in outputs.items() if output != expected
        ]
        if mismatches:
            raise ValueError(
                f"{case_id} subpixel contract mismatch: " + ", ".join(mismatches)
            )
        all_commands[case_id] = commands
        all_outputs[case_id] = outputs

    filter_success = all_outputs[
        "ftlcdfil.FT_Library_SetLcdFilter.success_sets_none_default_light"
    ]["pinned_c"]
    success_rows = filter_success.get("output", {}).get("outputs", [])
    expected_weights = {
        0: [0, 0, 0, 0, 0],
        1: [8, 77, 86, 77, 8],
        2: [0, 85, 86, 85, 0],
    }
    if (
        filter_success.get("status") != {"kind": "ok", "error_code": 0}
        or len(success_rows) != 3
        or any(
            row.get("error") != 0
            or row.get("library_weights") != expected_weights.get(row.get("filter"))
            for row in success_rows
        )
    ):
        raise ValueError(f"invalid enabled LCD filter state output: {filter_success}")

    invalid_rows = all_outputs[
        "ftlcdfil.FT_Library_SetLcdFilter.error_invalid_filter"
    ]["pinned_c"].get("output", {}).get("outputs", [])
    if (
        len(invalid_rows) != 4
        or any(row.get("error") == 0 for row in invalid_rows)
        or any(
            row.get("library_weights") != [8, 77, 86, 77, 8]
            for row in invalid_rows
        )
    ):
        raise ValueError(f"invalid LCD filter rejection state: {invalid_rows}")

    weights_success = all_outputs[
        "ftlcdfil.FT_Library_SetLcdFilterWeights.success_copies_five_weights"
    ]["pinned_c"]
    if weights_success.get("output") != {
        "error": 0,
        "library_weights": [16, 32, 64, 32, 16],
        "ignored_tail_bytes": [255],
    }:
        raise ValueError(f"invalid five-byte LCD weight copy: {weights_success}")

    geometry = all_outputs[
        (
            "ftlcdfil.FT_Library_SetLcdGeometry."
            "unimplemented_with_subpixel_filtering"
        )
    ]["pinned_c"]
    if (
        geometry.get("status") != {"kind": "error", "error_code": 7}
        or geometry.get("output")
        != {"error": 7, "feature_branch": "subpixel_rendering"}
    ):
        raise ValueError(f"invalid enabled-branch LCD geometry output: {geometry}")

    normalized = json.dumps(
        {
            case_id: outputs["pinned_c"]
            for case_id, outputs in all_outputs.items()
        },
        sort_keys=True,
        separators=(",", ":"),
    )
    ledger = {
        "schema_version": 1,
        "pinned_freetype_version": "2.14.3",
        "case_ids": list(routes),
        "measurement": (
            "Every enabled ClearType-style LCD setter route executes through "
            "an isolated pinned FreeType build, feature-matched Rust FFI, a "
            "separately linked C artifact, and the feature-matched WASM host. "
            "Stored weights prove presets, error-state preservation, and the "
            "five-byte copy boundary."
        ),
        "status": "exact",
        "lanes": 4,
        "routes": len(routes),
        "normalized_output_sha256": hashlib.sha256(
            normalized.encode()
        ).hexdigest(),
        "identity": {
            "option_header": str(option_header.relative_to(root)),
            "option_header_sha256": sha256(option_header),
            "pinned_library": str(pinned_library.relative_to(root)),
            "pinned_library_sha256": sha256(pinned_library),
            "pinned_oracle": str(pinned_oracle.relative_to(root)),
            "pinned_oracle_sha256": sha256(pinned_oracle),
            "fontdone_library": str(fontdone_library.relative_to(root)),
            "fontdone_library_sha256": sha256(fontdone_library),
            "external_c": str(external.relative_to(root)),
            "external_c_sha256": sha256(external),
            "rust_wasm_probe": str(probe.relative_to(root)),
            "rust_wasm_probe_sha256": sha256(probe),
            "external_build_manifest": str(build_manifest.relative_to(root)),
            "external_build_manifest_sha256": sha256(build_manifest),
        },
        "commands": all_commands,
        "outputs": all_outputs,
    }
    ledger_path = (
        root
        / "target"
        / "api-abi-audit"
        / "subpixel_rendering_enabled_contract_ledger.json"
    )
    ledger_path.parent.mkdir(parents=True, exist_ok=True)
    ledger_path.write_text(json.dumps(ledger, indent=2) + "\n")
    print(
        "Subpixel-rendering-enabled LCD contract: "
        f"4/4 lanes, {len(routes)}/{len(routes)} routes exact "
        f"sha256={ledger['normalized_output_sha256']}"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out", default="target/unified-fixtures/gen_fontdone_external"
    )
    parser.add_argument("--cargo-target-dir", default="target")
    parser.add_argument("--constants-dir", default="target/unified-fixtures")
    parser.add_argument(
        "--verify-optional-features-disabled",
        action="store_true",
    )
    parser.add_argument(
        "--verify-subpixel-rendering-enabled",
        action="store_true",
    )
    args = parser.parse_args()

    root = pathlib.Path(__file__).resolve().parent.parent
    output = root / args.out
    cargo_target_dir = root / args.cargo_target_dir
    build_dir = output.parent
    build_dir.mkdir(parents=True, exist_ok=True)
    audit_path = root / "target" / "api-abi-audit" / "api_abi_audit.json"
    if not audit_path.exists():
        raise SystemExit("missing API audit; run `make api-abi-audit` first")
    functions = json.loads(audit_path.read_text())["functions"]
    if len(functions) != 218:
        raise SystemExit(f"expected 218 pinned functions, found {len(functions)}")

    redirects = build_dir / "fontdone_external_trace_redirects.h"
    reapply = build_dir / "fontdone_external_trace_reapply.h"
    trace_source = build_dir / "fontdone_external_trace.c"
    oracle_object = build_dir / "gen_fontdone_external_oracle.o"
    trace_object = build_dir / "gen_fontdone_external_trace.o"
    build_manifest = build_dir / "gen_fontdone_external.build.json"
    write_if_changed(redirects, generate_redirect_header(functions))
    write_if_changed(reapply, generate_reapply_header(functions))
    write_if_changed(trace_source, generate_trace_source(functions))

    cc = os.environ.get("CC", "cc")
    source = root / "scripts" / "gen_unified_oracle.c"
    constants_dir = root / args.constants_dir
    pinned_include = root / "freetype" / "include"
    local_include = root / "fontdone-c-abi" / "include"
    library = shared_library(cargo_target_dir)

    compile_oracle = [
        cc,
        "-std=c11",
        "-DFONTDONE_EXTERNAL_TRACE=1",
        "-include",
        str(redirects),
        "-I",
        str(pinned_include),
        # The generated trace reapply header lives beside each external
        # optional-feature executable, not in the shared constants directory.
        "-I",
        str(build_dir),
        "-I",
        str(constants_dir),
        "-c",
        str(source),
        "-o",
        str(oracle_object),
    ]
    option_header = None
    if args.verify_subpixel_rendering_enabled:
        config_dir = (
            root / "target" / "oracle-config" / "subpixel-rendering-enabled"
        )
        option_header = (
            config_dir / "fontdone_ftconfig_subpixel_rendering_enabled.h"
        )
        compile_oracle[2:2] = [
            "-include",
            str(option_header),
            "-I",
            str(config_dir),
        ]
    compile_trace = [
        cc,
        "-std=c11",
        "-I",
        str(local_include),
        "-c",
        str(trace_source),
        "-o",
        str(trace_object),
    ]
    release = library.parent
    link = [
        cc,
        str(oracle_object),
        str(trace_object),
        "-L",
        str(release),
        f"-Wl,-rpath,{release}",
        "-lfontdone_c_abi",
        "-lm",
        "-o",
        str(output),
    ]
    for command in (compile_oracle, compile_trace, link):
        subprocess.run(command, check=True, cwd=root)
    dependency_inspection = inspect_dynamic_dependencies(output)

    manifest = {
        "schema_version": 1,
        "compiler": cc,
        "source": str(source.relative_to(root)),
        "source_sha256": sha256(source),
        "pinned_headers": str(pinned_include.relative_to(root)),
        "fontdone_header": str(
            (local_include / "fontdone_ffi.h").relative_to(root)
        ),
        "linked_fontdone_library": str(library.relative_to(root)),
        "linked_fontdone_library_sha256": sha256(library),
        "executable": str(output.relative_to(root)),
        "executable_sha256": sha256(output),
        "traced_functions": len(functions),
        "dependency_inspection": dependency_inspection,
        "commands": {
            "compile_oracle": compile_oracle,
            "compile_trace": compile_trace,
            "link": link,
        },
    }
    if option_header is not None:
        manifest["option_header"] = str(option_header.relative_to(root))
        manifest["option_header_sha256"] = sha256(option_header)
    build_manifest.write_text(json.dumps(manifest, indent=2) + "\n")
    if args.verify_optional_features_disabled:
        verify_lzw_disabled_contract(
            root,
            output,
            library,
            cargo_target_dir,
            build_manifest,
        )
        verify_bzip2_disabled_contract(
            root,
            output,
            library,
            cargo_target_dir,
            build_manifest,
        )
        verify_lcd_filtering_disabled_contract(
            root,
            output,
            library,
            cargo_target_dir,
            build_manifest,
        )
        verify_color_layers_disabled_contract(
            root,
            output,
            library,
            cargo_target_dir,
            build_manifest,
        )
    if args.verify_subpixel_rendering_enabled:
        verify_subpixel_rendering_enabled_contract(
            root,
            output,
            library,
            cargo_target_dir,
            build_manifest,
        )
    print(output)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        raise SystemExit(1) from error
