#!/usr/bin/env python3
"""Build the traced C consumer linked only to Fontdone's C ABI artifact.

The normal unified oracle and this executable compile the same C source against
the pinned FreeType headers.  The normal executable links to pinned FreeType;
this executable links to ``fontdone-c-abi`` and redirects every public
FreeType call through a generated tracing wrapper.  The runtime parity harness
uses those trace events to prove that a subject function was actually called.
"""

from __future__ import annotations

