#!/usr/bin/env python3
"""Build the unified C FreeType oracle helper used by fixture tests."""

import argparse
import os
import pathlib
import subprocess
import sys


def freetype_library(build_dir: pathlib.Path) -> pathlib.Path:
    candidates = [
        build_dir / "libfreetype.so",
        build_dir / "libfreetype.dylib",
    ]
    candidates.extend(sorted(build_dir.glob("libfreetype*.so*")))
    candidates.extend(sorted(build_dir.glob("libfreetype*.dylib")))
    candidates.extend(sorted(build_dir.glob("libfreetype*.a")))
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise FileNotFoundError(f"no libfreetype artifact found in {build_dir}")


def write_if_changed(path: pathlib.Path, contents: str) -> None:
    if path.exists() and path.read_text() == contents:
        return
    path.write_text(contents)


def configure_lzw_disabled_freetype(root: pathlib.Path) -> pathlib.Path:
    """Build the pinned source with its LZW option genuinely disabled."""

    config_dir = root / "target" / "oracle-config" / "lzw-disabled"
    config_dir.mkdir(parents=True, exist_ok=True)
    source_options = root / "freetype" / "include" / "freetype" / "config" / "ftoption.h"
    transformed_options = config_dir / "fontdone_ftoption_lzw_disabled.h"
    transformer = root / "freetype" / "builds" / "meson" / "process_ftoption_h.py"
    transformed = subprocess.run(
        [
            sys.executable,
            str(transformer),
            str(source_options),
            "--disable=FT_CONFIG_OPTION_USE_LZW",
        ],
        check=True,
        cwd=root,
        capture_output=True,
        text=True,
    )
    write_if_changed(
        transformed_options,
        transformed.stdout.rstrip("\n") + "\n",
    )
    preinclude = config_dir / "fontdone_ftconfig_lzw_disabled.h"
    write_if_changed(
        preinclude,
        "\n".join(
            [
                "/* Generated by scripts/build_unified_oracle.py; do not edit. */",
                "#ifndef FONTDONE_FTCONFIG_LZW_DISABLED_H_",
                "#define FONTDONE_FTCONFIG_LZW_DISABLED_H_",
                "#define FT_CONFIG_OPTIONS_H <fontdone_ftoption_lzw_disabled.h>",
                "#endif",
                "",
            ]
        )
    )
    project_include = config_dir / "lzw-disabled-options.cmake"
    write_if_changed(
        project_include,
        "\n".join(
            [
                "# Generated by scripts/build_unified_oracle.py; do not edit.",
                "add_compile_options(",
                '  "$<$<COMPILE_LANGUAGE:C>:-include>"',
                f'  "$<$<COMPILE_LANGUAGE:C>:{preinclude}>"',
                f'  "$<$<COMPILE_LANGUAGE:C>:-I{config_dir}>"',
                ")",
                "",
            ]
        )
    )

    build_dir = root / "freetype" / "build-lzw-disabled"
    subprocess.run(
        [
            "cmake",
            "-S",
            str(root / "freetype"),
            "-B",
            str(build_dir),
            "-DCMAKE_BUILD_TYPE=Release",
            "-DBUILD_SHARED_LIBS=ON",
            "-DFT_DISABLE_ZLIB=ON",
            "-DFT_DISABLE_PNG=ON",
            "-DFT_DISABLE_BZIP2=ON",
            "-DFT_DISABLE_BROTLI=ON",
            "-DFT_DISABLE_HARFBUZZ=ON",
            f"-DCMAKE_PROJECT_INCLUDE={project_include}",
        ],
        check=True,
        cwd=root,
    )
    subprocess.run(
        ["cmake", "--build", str(build_dir), "--parallel"],
        check=True,
        cwd=root,
    )
    return build_dir


