def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--variant",
        choices=(
            "default",
            "bzip2-enabled",
            "color-layers-disabled",
            "lzw-disabled",
            "subpixel-rendering-enabled",
        ),
        default="default",
    )
    parser.add_argument("--out")
    args = parser.parse_args()

    root = pathlib.Path(__file__).resolve().parent.parent
    default_out = {
        "default": "target/unified-fixtures/gen_unified_oracle",
        "bzip2-enabled": "target/unified-fixtures/gen_unified_oracle_bzip2_enabled",
        "color-layers-disabled": (
            "target/unified-fixtures/gen_unified_oracle_color_layers_disabled"
        ),
        "lzw-disabled": "target/unified-fixtures/gen_unified_oracle_lzw_disabled",
        "subpixel-rendering-enabled": (
            "target/unified-fixtures/gen_unified_oracle_subpixel_rendering_enabled"
        ),
    }[args.variant]
    out = root / (args.out or default_out)
    out.parent.mkdir(parents=True, exist_ok=True)
    source = root / "scripts" / "gen_unified_oracle.c"
    constants = root / "target" / "unified-fixtures" / "generated_constants.inc"
    generator = root / "scripts" / "generate_public_constants.py"
    script = pathlib.Path(__file__).resolve()
    freetype_build = {
        "default": lambda: root / "freetype" / "build",
        "bzip2-enabled": lambda: configure_bzip2_enabled_freetype(root),
        "color-layers-disabled": lambda: configure_color_layers_disabled_freetype(root),
        "lzw-disabled": lambda: configure_lzw_disabled_freetype(root),
        "subpixel-rendering-enabled": lambda: (
            configure_subpixel_rendering_enabled_freetype(root)
        ),
    }[args.variant]()
    library = freetype_library(freetype_build)

    subprocess.run(
        [
            os.environ.get("PYTHON", "python3"),
            str(generator),
            "--oracle-inc",
            str(constants.relative_to(root)),
        ],
        check=True,
        cwd=root,
    )

    if out.exists() and out.stat().st_mtime >= max(
        script.stat().st_mtime,
        source.stat().st_mtime,
        generator.stat().st_mtime,
        constants.stat().st_mtime,
        library.stat().st_mtime,
    ):
        print(out)
        return

    cmd = [
        os.environ.get("CC", "cc"),
        "-std=c11",
        "-I",
        str(root / "freetype" / "include"),
        "-I",
        str(constants.parent),
        str(source),
        "-L",
        str(freetype_build),
        f"-Wl,-rpath,{freetype_build}",
        "-lfreetype",
        "-lm",
        "-o",
        str(out),
    ]
    if args.variant == "default":
        cmd.insert(2, "-DFONTDONE_PINNED_ORACLE_VALIDATORS=1")
    elif args.variant == "subpixel-rendering-enabled":
        config_dir = root / "target" / "oracle-config" / args.variant
        cmd[2:2] = [
            "-include",
            str(config_dir / "fontdone_ftconfig_subpixel_rendering_enabled.h"),
            "-I",
            str(config_dir),
        ]
    subprocess.run(cmd, check=True, cwd=root)
    print(out)


if __name__ == "__main__":
    main()
